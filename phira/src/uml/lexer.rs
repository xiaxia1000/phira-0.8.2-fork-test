//! UML 脚本的词法分析层。
//!
//! UML 是 Phira 为活动页设计的「服务端下发 UI 描述语言」：活动页内容随运营活动
//! 变化，若把界面写死在客户端就得跟着发版，所以服务端下发一段脚本，客户端把它
//! 解析成元素树后渲染。本模块只承担第一层切分——把源字符串切成 [`Token`] 流；
//! 语法结构与表达式求值在 `super::parse` 中完成。
//!
//! 这里用 `logos` 而不是手写扫描器，是因为它在**编译期**把每条正则/固定串规则
//! 编译成一张 DFA 表，运行时对输入只做一遍线性匹配即可产出全部 token；既没有
//! 运行期正则编译或回溯开销（脚本解析发生在进入活动页时，卡顿会直接暴露给用户），
//! 又能把「文本块」「引号串」这类一眼看不出边界的结构写进同一张表里。

use logos::{Lexer, Logos};

/// UML 源码的 token 集合。
///
/// 与常规语言不同，UML 的 token 划分刻意混用了两类词：元素类型名
/// （`p`/`img`/`col`/`r`/`btn`/`let`）、属性名、变量名共用同一个 [`Token::Ident`]，
/// 由语法分析阶段按字符串再分派；而条件指令、文本块、引号串必须在词法阶段就
/// 成词，因为它们的内部会合法地出现空白、`:`、`>` 等别处有特殊含义的字符。
///
/// 空白（含换行与制表）被无条件跳过，因此脚本的元素之间可以任意换行排版。
#[derive(Logos, Debug, Clone, PartialEq)]
#[logos(error = String)]
#[logos(skip r"[ \t\n\f]+")]
pub enum Token {
    /// `{...}` 包裹的文本块，作为 `p`（文本）元素的正文，整体只算一个 token。
    /// 内部允许出现空格、冒号等字符（它们不会在此上下文被误词法化）。
    /// `}}` 是 `}` 的转义写法，规范化逻辑见 [`text_block`]。
    #[regex(r"\{([^}]|}})*}", text_block)]
    Text(String),
    /// `"..."` 双引号字符串，用于属性值需要按字面文本处理（而不是当作表达式）的场景，
    /// 例如按钮的 `action` 名字。内部不支持转义，见 [`quoted`]。
    #[regex(r#""[^"]*""#, quoted)]
    Quoted(String),

    /// `global` 关键字，声明跨帧保留的全局变量（如 `global $w = 1`）。
    /// 与元素里的 `let` 相对：`let` 绑定只在一帧的渲染过程中有效。
    #[token("global")]
    Global,

    /// `#>if-no-v2` 旧版条件语法标记。
    /// 它自身不带条件表达式，只声明「后面这段按 v2 之前的规则处理」；解析时
    /// 跳过标记本身并放行紧随其后的一个语句，从而让历史活动页脚本不必改写成
    /// `#>if true` 也能继续运行。
    #[token("#>if-no-v2")]
    IfNoV2,

    /// `#>if <expr>`：条件块开始，`expr` 于**渲染时**逐帧求值，非 0 视为真。
    #[token("#>if")]
    If,

    /// `#>else`：条件块的否定分支，与最近的 `#>if`/`#>elif` 配对。
    #[token("#>else")]
    Else,

    /// `#>elif <expr>`：链式分支，仅在前序分支均未命中时才会求值。
    #[token("#>elif")]
    ElseIf,

    /// `#>fi`：结束最近一个未闭合的条件块。
    #[token("#>fi")]
    EndIf,

    /// 通用标识符，兼任三类用途：元素类型名、属性名/变量名，以及以 `#>` 开头的
    /// 变换类元素（`#>rot`/`#>tr`/`#>alpha`/`#>mat`/`#>pop`）。
    /// 首字符另外允许 `@`（内建变量，如 `@btn`）与 `$`（全局变量）。
    /// 由于后续字符集含 `-`，`a-b` 会被整体识别成一个标识符而不是减法，
    /// 需要做减法时运算符两侧应留空格。
    #[regex("(#>)?[@a-zA-Z$_][a-zA-Z0-9-$_]*", |lex| lex.slice().to_owned())]
    Ident(String),

    /// 数值字面量，支持小数与科学计数法。前导 `-` 会被并入 token，因此 `x -1`
    /// 会被切成标识符 `x` 与数值 `-1` 两个 token（而非减法）；减法同样要写成
    /// `x - 1`。数值解析失败时回调返回 `None`，由 `logos` 转成词法错误。
    #[regex("-?[0-9]*[.]?[0-9]+(?:[eE][+-]?[0-9]+)?", |lex| lex.slice().parse().ok())]
    Number(f32),

    /// 布尔字面量。只有属性配置（`parse::take_config`）会直接消费它——
    /// 表达式解析里布尔不是原子，会退化成变量名。
    #[regex("true|false", |lex| lex.slice() == "true")]
    Bool(bool),

    /// `#` 起头直到行尾的注释，由 `logos::Skip` 直接丢弃。
    /// 首个字符不允许是 `>`，这样 `#>` 开头的条件/变换指令不会被误当注释吃掉。
    #[regex("#([^>][^\n]*)?", |_| logos::Skip)]
    Comment,

    /// `(`。注意变体名沿用了「花括号」的说法，但实际字面量是圆括号：UML 里
    /// `{}` 已被文本块独占（见 [`Token::Text`]），元素属性块与函数调用、括号
    /// 分组一律使用 `()`。属性块的左界就是靠它来判断「本元素是否带配置」。
    #[token("(")]
    LBrace,
    /// `)`：属性块、函数调用实参表与括号分组的右界。
    #[token(")")]
    RBrace,
    /// `[`：矩形字面量 `[x, y, w, h]` 的左界。
    #[token("[")]
    LBracket,
    /// `]`：矩形字面量的右界。
    #[token("]")]
    RBracket,
    /// `,`：属性之间、函数实参之间、矩形分量之间的分隔符。
    #[token(",")]
    Comma,
    /// `:`：属性名与属性值之间的分隔符（`name: value`）。
    #[token(":")]
    Colon,
    /// `=`：变量绑定 `let x = expr` / `global x = expr` 里的赋值号。
    #[token("=")]
    Assign,
    /// `.`：变量字段访问 `r.w`、`@btn.cnt`。
    #[token(".")]
    Period,
    /// `+`：加法；对矩形是四周扩张（见 `RawExpr::eval`）。
    #[token("+")]
    Add,
    /// `-`：减法；对矩形是四周收缩。
    #[token("-")]
    Sub,
    /// `*`：乘法（仅浮点）。
    #[token("*")]
    Mul,
    /// `/`：除法（仅浮点，不做除零检查）。
    #[token("/")]
    Div,
    /// `<=`：小于等于，求值结果为 0.0/1.0。
    #[token("<=")]
    Le,
    /// `>=`：大于等于，求值结果为 0.0/1.0。
    #[token(">=")]
    Ge,
    /// `<`：小于，求值结果为 0.0/1.0。
    #[token("<")]
    Lt,
    /// `>`：大于，求值结果为 0.0/1.0。
    #[token(">")]
    Gt,
    /// `==`：相等，求值结果为 0.0/1.0。
    #[token("==")]
    Eq,
    /// `!=`：不等，求值结果为 0.0/1.0。
    #[token("!=")]
    Neq,
}

/// [`Token::Text`] 的取值回调：把匹配到的整段 `{...}` 规范化成正文文本。
///
/// 处理规则及其原因：
/// 1. 先把转义写法 `}}` 还原成单个 `}`，让正文能包含右花括号；
/// 2. 掐掉最外层的一对花括号，并去掉行首空格与行尾空白——这些空白只是作者
///    在脚本里排版时敲进去的，不该出现在渲染结果中；
/// 3. 若正文以换行开头（即多行文本块），则取出首行由换行/空格/制表组成的缩进串，
///    把正文中每一处同样的缩进串替换成单个换行。这相当于「按源码缩进反缩进」：
///    作者可以自然地把长文本按缩进折行，而渲染时不会多出对齐用的空格。
///
/// 不变量：进入第 3 步分支时首字符必为 `\n`，故 `ident` 一定非空；
/// 否则 `replace("", "\n")` 会在每个字符间插入换行，正文会被切碎。
fn text_block(lexer: &Lexer<Token>) -> String {
    let s = lexer.slice().replace("}}", "}");
    let s = s[1..(s.len() - 1)].trim_start_matches(' ').trim_end();
    if s.starts_with('\n') {
        let ident: String = s.chars().take_while(|&it| it == '\n' || it == ' ' || it == '\t').collect();
        s[ident.len()..].replace(&ident, "\n")
    } else {
        s.to_owned()
    }
}

/// [`Token::Quoted`] 的取值回调：去掉首尾的一对双引号，返回内部字面内容。
/// 引号内不处理任何转义（词法正则本身就排除了 `"`），因此这类字符串无法包含
/// 双引号本身——需要更多字符时应当使用文本块。
fn quoted(lexer: &Lexer<Token>) -> String {
    let s = lexer.slice();
    s[1..(s.len() - 1)].to_owned()
}
